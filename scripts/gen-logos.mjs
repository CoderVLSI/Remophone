// Regenerates src/duet/logos.js: brand marks as SVG path data, so the app ships only the
// handful it uses instead of the whole icon set. Run: node scripts/gen-logos.mjs
// Source: Simple Icons (CC0). Slack and DocuSign were removed from current releases, so
// those two come from v11.14.0, installed as "simple-icons-legacy".
import fs from "node:fs";
import * as current from "simple-icons";
import * as legacy from "simple-icons-legacy";

const WANT = [
  ["gmail", current, "siGmail"],
  ["googlecalendar", current, "siGooglecalendar"],
  ["googledrive", current, "siGoogledrive"],
  ["slack", legacy, "siSlack"],
  ["quickbooks", current, "siQuickbooks"],
  ["hubspot", current, "siHubspot"],
  ["docusign", legacy, "siDocusign"],
  ["calendly", current, "siCalendly"],
  ["stripe", current, "siStripe"],
  ["shopify", current, "siShopify"],
];

const out = {};
for (const [key, source, name] of WANT) {
  const icon = source[name];
  if (!icon) throw new Error(`Missing icon ${name}`);
  out[key] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path };
}

const body = `// GENERATED by scripts/gen-logos.mjs from Simple Icons (CC0). Do not edit by hand.
// Brand names and marks belong to their owners and are used only to identify the service.
export const LOGOS = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(new URL("../src/duet/logos.js", import.meta.url), body);
console.log("wrote", Object.keys(out).join(", "));
